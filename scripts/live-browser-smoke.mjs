import {chromium} from '@playwright/test';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
const url=process.env.SMOKE_URL || 'http://127.0.0.1:4173/podlingua/';
const fixture=process.argv[2];
if(!fixture)throw new Error('Pass a real speech WAV fixture path. No hosted API is called.');
const browser=await chromium.launch({headless:true,args:['--disable-dev-shm-usage']});
const context=await browser.newContext();
const page=await context.newPage();const errors=[],requests=[];
page.on('pageerror',e=>{errors.push(e.message);console.log('PAGE ERROR',e.message);});
page.on('requestfailed',r=>console.log('REQUEST FAILED',r.url(),r.failure()));
page.on('request',r=>{if(!r.url().startsWith(url)&&!r.url().startsWith('blob:'))requests.push({method:r.method(),url:r.url()});});
page.on('dialog',d=>d.accept());
const started=Date.now();
try{
 await page.goto(url);
 await page.getByLabel('Import audio',{exact:true}).setInputFiles({name:'Real JFK speech.wav',mimeType:'audio/wav',buffer:await readFile(fixture)});
 await page.getByRole('heading',{name:'Real JFK speech',exact:true}).waitFor();
 await page.getByRole('button',{name:'Engine settings'}).click();
 await page.locator('#source').fill('en');await page.locator('#target').fill('fr');await page.locator('#download-consent').check();
 await page.getByLabel('Translation model',{exact:true}).fill('Xenova/opus-mt-en-fr');
 await page.getByRole('button',{name:'Done',exact:true}).click();
 await page.getByRole('button',{name:'Transcribe episode'}).click();
 await page.waitForFunction(()=>!document.querySelector('#cancel').hidden,null,{timeout:10000});
 await page.waitForFunction(()=>document.querySelector('#cancel').hidden,null,{timeout:600000});
 console.log('ASR STATUS',await page.locator('#status').innerText());
 const asr=await page.locator('.original').allTextContents();
 console.log('REAL ASR',JSON.stringify(asr));
 if(!asr.join(' ').toLowerCase().includes('americans'))throw new Error('Real speech transcription did not contain expected audible word americans.');
 await page.getByRole('button',{name:'Translate transcript'}).click();
 await page.waitForFunction(()=>!document.querySelector('#cancel').hidden,null,{timeout:10000});
 await page.waitForFunction(()=>document.querySelector('#cancel').hidden,null,{timeout:600000});
 console.log('TRANSLATION STATUS',await page.locator('#status').innerText());
 const translated=await page.locator('.translation').allTextContents();
 console.log('REAL TRANSLATION',JSON.stringify(translated));
 if(!translated.length||translated.some(t=>t.includes('new perspective away')))throw new Error('Local translation did not produce translated segments.');
 await mkdir('/home/hermes/.hermes/cache/scratch/podlingua-evidence',{recursive:true});
 const screenshot='/home/hermes/.hermes/cache/scratch/podlingua-evidence/live-desktop.png';
 await page.screenshot({path:screenshot,fullPage:true});
 const report={url,elapsedSeconds:(Date.now()-started)/1000,asr,translated,errors,requests,model:'Xenova/whisper-tiny',translationModel:'Xenova/opus-mt-en-fr',fixture,paidRequests:0};
 await writeFile('/home/hermes/.hermes/cache/scratch/podlingua-evidence/live-smoke.json',JSON.stringify(report,null,2));
 if(errors.length)throw new Error('Browser errors occurred.');
 console.log('REAL LOCAL BROWSER INFERENCE PASSED',screenshot);
}finally{await browser.close();}
